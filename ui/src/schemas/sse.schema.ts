import * as z from "zod"

// ---------------------------------------------------------------------------
// Base payload — present on every SSE event from api_server.py
// ---------------------------------------------------------------------------

const baseSsePayload = z.object({
  session_id: z.string().default(""),
  run_id: z.string().default(""),
  seq: z.number().default(0),
  ts: z.number().default(0),
})

// ---------------------------------------------------------------------------
// Individual event schemas
// ---------------------------------------------------------------------------

export const sseRunStartedSchema = baseSsePayload.extend({
  user_message: z.object({
    role: z.string(),
    content: z.string(),
  }),
})

export const sseMessageStartedSchema = baseSsePayload.extend({
  message: z.object({
    id: z.string(),
    role: z.string(),
  }),
})

export const sseAssistantDeltaSchema = baseSsePayload.extend({
  message_id: z.string(),
  delta: z.string(),
})

export const sseToolStartedSchema = baseSsePayload.extend({
  message_id: z.string(),
  tool_name: z.string(),
})

export const sseToolProgressSchema = baseSsePayload.extend({
  message_id: z.string(),
  tool_name: z.string(),
  delta: z.string().default(""),
})

export const sseToolCompletedSchema = baseSsePayload.extend({
  message_id: z.string(),
  tool_name: z.string(),
  preview: z.string().optional(),
  args: z.unknown().optional(),
})

export const sseUsageSchema = z.object({
  input_tokens: z.number().optional(),
  output_tokens: z.number().optional(),
  total_tokens: z.number().optional(),
  cache_read_tokens: z.number().optional(),
  cache_write_tokens: z.number().optional(),
  reasoning_tokens: z.number().optional(),
  /** Estimated spend (USD) for this step/run — host-computed from the catalog. */
  cost: z.number().optional(),
  /** Wall time (ms) of the step/run — powers the last-run summary line. */
  duration_ms: z.number().optional(),
  /** Model that produced this step (per-message metadata). */
  model: z.string().nullish(),
})

export const sseAssistantCompletedSchema = baseSsePayload.extend({
  message_id: z.string(),
  content: z.string(),
  completed: z.boolean().default(true),
  partial: z.boolean().default(false),
  interrupted: z.boolean().default(false),
  finish_reason: z.string().nullish(),
  reasoning_content: z.string().nullish(),
  usage: sseUsageSchema.nullish(),
  /** Images generated by the model this step (image-output models). */
  images: z.array(z.string()).nullish(),
})

export const sseRunCompletedSchema = baseSsePayload.extend({
  message_id: z.string().default(""),
  completed: z.boolean().default(true),
  messages: z.array(z.unknown()).default([]),
  usage: sseUsageSchema.nullable().default(null),
  /** Session running spend (USD) — drives the footer's cost readout. */
  session_cost: z.number().nullish(),
  /** Context window (tokens) of the model that ran — for the % display. */
  context_window: z.number().nullish(),
})

export const sseErrorSchema = baseSsePayload.extend({
  message: z.string(),
})

export const sseDoneSchema = baseSsePayload

// ---------------------------------------------------------------------------
// Event name → schema map
// ---------------------------------------------------------------------------

/**
 * Lookup table from SSE event name to its Zod schema.
 * Used by the stream dispatcher for zero-trust payload validation.
 */
export const sseEventSchemas = {
  "run.started": sseRunStartedSchema,
  "message.started": sseMessageStartedSchema,
  "assistant.delta": sseAssistantDeltaSchema,
  "tool.started": sseToolStartedSchema,
  "tool.progress": sseToolProgressSchema,
  "tool.completed": sseToolCompletedSchema,
  "assistant.completed": sseAssistantCompletedSchema,
  "run.completed": sseRunCompletedSchema,
  error: sseErrorSchema,
  done: sseDoneSchema,
} as const

export type SseEventSchemas = typeof sseEventSchemas
export type SseEventKey = keyof SseEventSchemas
